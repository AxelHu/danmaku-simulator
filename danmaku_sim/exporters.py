"""Portable exports of synthetic comments, with no executable text injection."""
from __future__ import annotations

from collections import Counter
import hashlib
import html
import json
import math
from pathlib import Path
import unicodedata
import xml.etree.ElementTree as ET


def _plain(value: object) -> str:
    # XML 1.0, ASS and ordinary players disagree about C0 controls and lone
    # surrogates. Keep displayable Unicode only and flatten accidental newlines.
    text = " ".join(str(value).split())
    return "".join(c for c in text if unicodedata.category(c) not in {"Cc", "Cf", "Cs"}
                   and ord(c) not in {0xFFFE, 0xFFFF})


def escape_html(text: str) -> str:
    return html.escape(_plain(text), quote=True)


def escape_ass(text: str) -> str:
    """Use visible full-width equivalents for ASS control syntax.

    Backslash escapes are renderer-dependent, so literal braces and backslashes
    are normalized instead of pretending that ``\\{`` is universally safe.
    Original wording is preserved losslessly in JSON; ASS favors inert display.
    """
    return _plain(text).replace("\\", "＼").replace("{", "｛").replace("}", "｝")


def _prepared(comments: list[dict]) -> tuple[list[dict], Counter]:
    prepared = []
    rejected: Counter = Counter()
    for comment in comments:
        try:
            time = float(comment["time"])
            if not math.isfinite(time) or time < 0:
                raise ValueError("invalid time")
            text = _plain(comment["text"])
            if not text:
                raise ValueError("empty text")
            size = max(12, min(64, int(comment.get("size", 25))))
            color = max(0, min(0xFFFFFF, int(comment.get("color", 0xFFFFFF))))
        except (KeyError, TypeError, ValueError, OverflowError):
            rejected["invalid_comment"] += 1
            continue
        prepared.append({**comment, "time": time, "text": text, "size": size, "color": color})
    prepared.sort(key=lambda comment: (comment["time"], str(comment.get("id", ""))))
    return prepared, rejected


def write_json(data: dict | list, path: str | Path) -> dict:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    return {"path": str(path), "format": "json"}


def write_xml(comments: list[dict], path: str | Path) -> dict:
    """Write a Bilibili-compatible XML timing stream, clearly marked synthetic."""
    prepared, rejected = _prepared(comments)
    root = ET.Element("i")
    root.append(ET.Comment("Synthetic danmaku generated by danmaku-simulator; not original viewer comments."))
    ET.SubElement(root, "chatserver").text = "synthetic.local"
    ET.SubElement(root, "chatid").text = "0"
    ET.SubElement(root, "mission").text = "0"
    ET.SubElement(root, "maxlimit").text = str(len(prepared))
    ET.SubElement(root, "state").text = "0"
    ET.SubElement(root, "real_name").text = "0"
    ET.SubElement(root, "source").text = "synthetic"
    for index, comment in enumerate(prepared):
        viewer = str(comment.get("virtual_viewer_id", comment.get("persona", "viewer")))
        actor = hashlib.sha256(viewer.encode()).hexdigest()[:8]
        row_id = int.from_bytes(hashlib.sha256(str(comment.get("id", index)).encode()).digest()[:7], "big")
        timing = format(comment["time"], ".6f").rstrip("0").rstrip(".") or "0"
        attributes = f"{timing},1,{comment['size']},{comment['color']},0,0,{actor},{row_id}"
        ET.SubElement(root, "d", {"p": attributes}).text = comment["text"]
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    ET.ElementTree(root).write(path, encoding="utf-8", xml_declaration=True)
    return {"path": str(path), "format": "xml", "written": len(prepared), "dropped": dict(rejected)}


def _ass_time(ticks: int) -> str:
    hours, remainder = divmod(ticks, 360000)
    minutes, remainder = divmod(remainder, 6000)
    seconds, centiseconds = divmod(remainder, 100)
    return f"{hours}:{minutes:02}:{seconds:02}.{centiseconds:02}"


def _text_width(text: str, font_size: float) -> float:
    units = sum(0 if unicodedata.combining(c) else
                1.08 if unicodedata.east_asian_width(c) in {"W", "F"} else .65 for c in text)
    return max(font_size, units * font_size)


def write_ass(comments: list[dict], path: str | Path, width: int = 1920, height: int = 1080) -> dict:
    """Write scrolling ASS with constant velocity and collision-aware lanes.

    Equal pixel velocity prevents shorter comments catching longer ones. A lane
    is available when the preceding tail has cleared the launch point. Export
    never shifts a comment's meaning to a later scene; an overloaded lane set
    drops that comment and reports it instead. A provided end_time clips motion
    at the video ending while preserving velocity.
    """
    if isinstance(width, bool) or isinstance(height, bool) or width < 160 or height < 90:
        raise ValueError("ASS dimensions must be at least 160 by 90")
    if int(width) != width or int(height) != height:
        raise ValueError("ASS dimensions must be integers")
    width, height = int(width), int(height)
    prepared, rejected = _prepared(comments)
    base_font = max(14, round(height * .038))
    fonts = [max(12, round(base_font * comment["size"] / 25)) for comment in prepared]
    lane_height = max(fonts, default=base_font) * 1.28
    lane_count = max(1, int(height * .60 / lane_height))
    lanes = [0.0] * lane_count
    speed = width / 6.4
    gap = max(18, base_font * .8)
    margin = max(8, width * .008)
    lines = ["[Script Info]", "Title: Synthetic danmaku", "ScriptType: v4.00+",
             f"PlayResX: {width}", f"PlayResY: {height}", "WrapStyle: 2",
             "ScaledBorderAndShadow: yes", "; Generated comments; original viewer data is not represented.",
             "", "[V4+ Styles]",
             "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
             f"Style: Danmaku,Noto Sans CJK SC,{base_font},&H00FFFFFF,&H00FFFFFF,&H00000000,&H80000000,0,0,0,0,100,100,0,0,1,1.5,0,7,0,0,0,1",
             "", "[Events]", "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"]
    written = 0
    for comment, font_size in zip(prepared, fonts):
        # ASS precision is centiseconds. Round forwards, never before a causal cutoff.
        start_ticks = math.ceil((comment["time"] - 1e-10) * 100)
        start = start_ticks / 100
        lane = next((index for index, ready in enumerate(lanes) if ready <= start + 1e-9), None)
        if lane is None:
            rejected["lane_overflow"] += 1
            continue
        text = escape_ass(comment["text"])
        text_width = _text_width(text, font_size)
        natural_end = start + (width + text_width + margin * 2) / speed
        end = natural_end
        try:
            requested_end = float(comment.get("end_time", natural_end))
            if math.isfinite(requested_end):
                end = min(end, requested_end)
        except (TypeError, ValueError, OverflowError):
            pass
        end_ticks = math.floor((end + 1e-10) * 100)
        if end_ticks <= start_ticks:
            rejected["no_display_time"] += 1
            continue
        end = end_ticks / 100
        x_start = width + margin
        x_end = x_start - speed * (end - start)
        y = margin + lane * lane_height
        color = comment["color"]
        bgr = f"{color & 255:02X}{(color >> 8) & 255:02X}{(color >> 16) & 255:02X}"
        tags = "{" + f"\\an7\\fs{font_size}\\c&H{bgr}&\\move({x_start:.2f},{y:.2f},{x_end:.2f},{y:.2f})" + "}"
        lines.append(f"Dialogue: 0,{_ass_time(start_ticks)},{_ass_time(end_ticks)},Danmaku,,0,0,0,,{tags}{text}")
        lanes[lane] = min(end, start + (text_width + gap) / speed)
        written += 1
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")
    return {"path": str(path), "format": "ass", "written": written, "dropped": dict(rejected),
            "lanes": lane_count, "pixels_per_second": speed}
